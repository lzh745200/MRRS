#!/usr/bin/env python3
"""Verify build metadata inside the PyInstaller onedir backend artifact.

H12 gate (2026-10-14): the onedir output must contain
_internal/app/core/_build_info.json generated by CI
(scripts/generate_build_info.py, builder == "ci"). Without this gate the
frozen backend silently falls back to the dev fingerprint
(git_hash="dev", builder="dev") and release traceability is lost.

All output is ASCII-only: en-US CI runners default to cp1252 stdout and any
non-ASCII print raises UnicodeEncodeError (see the PYTHONUTF8 note in
.github/workflows/build-windows.yml). Do not add non-ASCII strings here.
"""

import argparse
import json
import os
import sys


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Verify _build_info.json inside the onedir backend artifact"
    )
    parser.add_argument(
        "--backend-dir",
        default=os.path.join("backend", "dist", "assistance-backend"),
        help="onedir output directory (contains assistance-backend.exe and _internal/)",
    )
    args = parser.parse_args()

    info_path = os.path.join(
        args.backend_dir, "_internal", "app", "core", "_build_info.json"
    )

    if not os.path.isfile(info_path):
        print("FAIL: build info file missing: %s" % info_path)
        print(
            "       assistance-backend.spec must include app/core/_build_info.json"
            " in datas (CI generates it before packaging)"
        )
        return 1

    try:
        with open(info_path, "r", encoding="utf-8") as fh:
            data = json.load(fh)
    except Exception as exc:
        print("FAIL: cannot parse %s: %s" % (info_path, exc))
        return 1

    if not isinstance(data, dict):
        print("FAIL: build info is not a JSON object: %s" % type(data).__name__)
        return 1

    builder = str(data.get("builder", ""))
    if not builder or builder == "dev":
        print(
            'FAIL: builder is "%s" (expected "ci");'
            " artifact carries a dev/stale build fingerprint" % builder
        )
        return 1

    print(
        "OK: build info present (version=%s, git_hash=%s, build_time=%s, builder=%s)"
        % (
            data.get("version", ""),
            data.get("git_hash", ""),
            data.get("build_time", ""),
            builder,
        )
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
